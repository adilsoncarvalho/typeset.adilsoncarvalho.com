/* Derives tools/rename-map-2.0-singular.json from the current spec.json:
   every plural section id gets its singular id, and every element id under
   that section gets the same rewrite applied to its section-id prefix.

   This map is generated, never hand-edited, and it is a distinct file from
   tools/rename-map.json — that file is frozen at 1.x -> 2.0.0 and describes
   spec 1.0.0 ids that the current spec.json does not carry, so it cannot be
   regenerated from the spec and must not gain these rows. This map instead
   covers the 2.0.0 plural -> 2.0.0 singular step, and tools/codemod-names.mjs
   chains it after the frozen map.

   Refuses to write an incomplete map: unless every plural section and every
   element under one has a row, it exits non-zero and prints what is missing,
   rather than silently shipping a hole.

   Run: node tools/build-singular-map.mjs
*/

import { readFileSync, writeFileSync } from 'node:fs';

const OUT_PATH = 'tools/rename-map-2.0-singular.json';

const spec = JSON.parse(readFileSync('spec.json', 'utf8'));

function singularize(id) {
  if (id.endsWith('ies')) return `${id.slice(0, -3)}y`;
  if (id.endsWith('s')) return id.slice(0, -1);
  throw new Error(`cannot singularize section id: ${id}`);
}

const pluralSections = spec.sections.filter((sec) => /s$/.test(sec.id));

const sections = {};
const elements = {};

for (const sec of pluralSections) {
  const singularId = singularize(sec.id);
  sections[sec.id] = singularId;
  for (const el of sec.elements || []) {
    if (!el.id.startsWith(`${sec.id}-`)) continue;
    elements[el.id] = singularId + el.id.slice(sec.id.length);
  }
}

/* Refuse to emit an incomplete map. This re-derives the expected rows from
   spec.json in a second, independent pass over the same source of truth,
   rather than trusting the loop above — the loop above is exactly the kind
   of code that shipped a map missing six classes elsewhere in this project,
   silently, because nothing checked its output against the spec afterwards. */
const missing = [];
for (const sec of spec.sections) {
  if (!/s$/.test(sec.id)) continue;
  if (!(sec.id in sections)) missing.push(`section: ${sec.id}`);
  for (const el of sec.elements || []) {
    if (!el.id.startsWith(`${sec.id}-`)) continue;
    if (!(el.id in elements)) missing.push(`element: ${el.id} (section ${sec.id})`);
  }
}

if (missing.length > 0) {
  console.error(`build-singular-map: refusing to write an incomplete map — missing ${missing.length} row(s):`);
  for (const m of missing) console.error(`  - ${m}`);
  process.exit(1);
}

const note = 'Generated by tools/build-singular-map.mjs from the current spec.json: '
  + 'every plural section id and every element id under it, singularised. '
  + 'Regenerate rather than hand-edit. Do not merge these rows into '
  + 'tools/rename-map.json, which is frozen at 1.x -> 2.0.0 — this map covers '
  + 'the separate 2.0.0 plural -> 2.0.0 singular step, and '
  + 'tools/codemod-names.mjs chains it after that one.';

writeFileSync(OUT_PATH, `${JSON.stringify({ note, sections, elements }, null, 2)}\n`);

console.log(`build-singular-map: wrote ${Object.keys(sections).length} section row(s) and ${Object.keys(elements).length} element row(s) to ${OUT_PATH}`);
